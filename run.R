## run.R
## Single entry point for the build. Steps, their order, inputs and outputs are in
## pipeline.csv (paths relative to MV_BUILD; see R/config.R).
##
##   Rscript run.R [database|checks|multiverse|all] [options]
##     --dry-run       list what would run (and why), run nothing
##     --from <id>     force a rebuild from step <id> on (within the chosen stages)
##     --only <id,..>  run just these steps (forced)
##     --graph         write the step dependency graph (Mermaid) to env/pipeline_graph.md
##
## Each step runs in a fresh Rscript process from the project folder, with its log
## in MV_BUILD/logs/<id>.log. A step is skipped when all its outputs exist and are
## newer than its inputs and its script (make-style); steps without declared outputs
## always run. A declared input that is missing (and not produced by an earlier step
## of this run) stops the run before anything starts; a step that exits with an
## error, or does not write its outputs, stops it too. At the end MV_BUILD/MANIFEST.csv
## lists every declared output (path, bytes, sha256, step, modified).
## Default stage: database. "all" = database, checks, multiverse.

source( "R/config.R" )                      # BUILD, PROJECT_ROOT (base R only)

args <- commandArgs( TRUE )
opt_val <- function( flag ) { i <- match( flag, args ); if ( is.na( i ) || i == length( args ) ) NA_character_ else args[ i + 1 ] }
DRY   <- "--dry-run" %in% args
GRAPH <- "--graph" %in% args
FROM  <- opt_val( "--from" )
ONLY  <- opt_val( "--only" )
ONLY  <- if ( is.na( ONLY ) ) character( 0 ) else strsplit( ONLY, "," )[[ 1 ]]
pos   <- args[ !startsWith( args, "--" ) & !args %in% c( FROM, paste( ONLY, collapse = "," ) ) ]
STAGES <- c( "database", "checks", "multiverse" )
target <- if ( length( pos ) ) pos[ 1 ] else "database"
stages <- if ( target == "all" ) STAGES else target
if ( !all( stages %in% STAGES ) ) stop( "unknown stage '", target, "' (database, checks, multiverse, all)" )

p <- read.csv( "pipeline.csv", colClasses = "character", na.strings = character( 0 ) )
split_paths <- function( x ) { x <- trimws( strsplit( x, ";", fixed = TRUE )[[ 1 ]] ); x[ nzchar( x ) ] }
p$ins  <- lapply( p$inputs, split_paths )
p$outs <- lapply( p$outputs, split_paths )
stopifnot( !anyDuplicated( p$id ), all( file.exists( p$script ) ) )

## producer of each declared output (an output belongs to one step)
prod <- do.call( rbind, lapply( seq_len( nrow( p ) ), function( i )
  if ( length( p$outs[[ i ]] ) ) data.frame( path = p$outs[[ i ]], id = p$id[ i ] ) ) )
if ( anyDuplicated( prod$path ) ) stop( "declared by two steps: ", paste( unique( prod$path[ duplicated( prod$path ) ] ), collapse = ", " ) )
## every input made by the pipeline must come from an earlier step
for ( i in seq_len( nrow( p ) ) ) for ( f in p$ins[[ i ]] ) {
  j <- match( f, prod$path )
  if ( !is.na( j ) && match( prod$id[ j ], p$id ) >= i )
    stop( "step ", p$id[ i ], " reads ", f, ", which step ", prod$id[ j ], " writes later: fix the order in pipeline.csv" )
}

## ---- dependency graph ----------------------------------------------------------------
if ( GRAPH ) {
  ed <- unique( do.call( rbind, lapply( seq_len( nrow( p ) ), function( i ) {
    j <- match( p$ins[[ i ]], prod$path ); j <- j[ !is.na( j ) ]
    if ( length( j ) ) data.frame( from = prod$id[ j ], to = p$id[ i ] ) } ) ) )
  node <- function( id ) paste0( "s", gsub( "[^A-Za-z0-9]", "_", id ) )
  L <- c( "# Pipeline dependency graph", "",
          "Generated by `Rscript run.R --graph` from `pipeline.csv`. An edge means the later step",
          "reads a file the earlier step writes (raw sources are not shown).", "", "```mermaid", "flowchart LR" )
  for ( s in STAGES ) {
    q <- p[ p$stage == s, ]
    L <- c( L, paste0( "  subgraph ", s ),
            sprintf( "    %s[\"%s %s\"]", node( q$id ), q$id, sub( "^R/[0-9a-z]+_|\\.R$", "", sub( "\\.R$", "", q$script ) ) ),
            "  end" )
  }
  L <- c( L, sprintf( "  %s --> %s", node( ed$from ), node( ed$to ) ), "```" )
  writeLines( L, file.path( "env", "pipeline_graph.md" ) )
  cat( "wrote env/pipeline_graph.md:", nrow( p ), "steps,", nrow( ed ), "edges\n" )
  quit( save = "no" )
}

## ---- plan --------------------------------------------------------------------------------
sel <- which( p$stage %in% stages )
if ( length( ONLY ) ) {
  if ( !all( ONLY %in% p$id ) ) stop( "unknown step: ", paste( setdiff( ONLY, p$id ), collapse = ", " ) )
  sel <- which( p$id %in% ONLY )
}
if ( !is.na( FROM ) && !FROM %in% p$id[ sel ] ) stop( "--from ", FROM, " is not a step of: ", paste( stages, collapse = ", " ) )
forced <- if ( length( ONLY ) ) p$id[ sel ] else if ( !is.na( FROM ) ) p$id[ sel[ sel >= match( FROM, p$id ) ] ] else character( 0 )

bpath <- function( f ) file.path( BUILD, f )
expand <- function( f ) { g <- Sys.glob( bpath( f ) ); if ( grepl( "[*?]", f ) ) g else bpath( f ) }
exists_all <- function( fs ) all( vapply( fs, function( f ) length( expand( f ) ) > 0 && all( file.exists( expand( f ) ) ), logical( 1 ) ) )
mtimes <- function( fs ) unlist( lapply( fs, function( f ) file.mtime( expand( f ) ) ) )

cat( sprintf( "BUILD = %s; stages: %s\n", BUILD, paste( stages, collapse = ", " ) ) )
will_make <- character( 0 )                 # outputs that steps of this run will write
plan <- data.frame( id = p$id[ sel ], action = "", why = "" )
for ( k in seq_along( sel ) ) {
  i <- sel[ k ]; ins <- p$ins[[ i ]]; outs <- p$outs[[ i ]]
  miss <- ins[ !vapply( ins, function( f ) exists_all( f ), logical( 1 ) ) & !ins %in% will_make ]
  if ( length( miss ) ) stop( "step ", p$id[ i ], ": missing input(s) ", paste( miss, collapse = ", " ),
                              if ( any( miss %in% prod$path ) ) " (run the steps that write them first, or include their stage)" else "" )
  why <- if ( p$id[ i ] %in% forced ) "forced"
         else if ( !length( outs ) ) "no declared outputs"
         else if ( !exists_all( outs ) ) "output missing"
         else if ( any( ins %in% will_make ) ) "an input is rebuilt in this run"
         else {
           t_out <- min( mtimes( outs ) ); t_in <- max( c( mtimes( ins ), file.mtime( p$script[ i ] ) ) )
           if ( t_in > t_out ) "inputs or script newer than outputs" else ""
         }
  plan$action[ k ] <- if ( nzchar( why ) ) "run" else "skip"
  plan$why[ k ] <- if ( nzchar( why ) ) why else "up to date"
  if ( nzchar( why ) ) will_make <- c( will_make, outs )
}
print( plan, row.names = FALSE, right = FALSE )
if ( DRY ) quit( save = "no" )

## ---- run -----------------------------------------------------------------------------------
logs <- file.path( BUILD, "logs" ); dir.create( logs, recursive = TRUE, showWarnings = FALSE )
rscript <- file.path( R.home( "bin" ), if ( .Platform$OS.type == "windows" ) "Rscript.exe" else "Rscript" )
timing <- data.frame( id = character( 0 ), seconds = numeric( 0 ) )
for ( k in which( plan$action == "run" ) ) {
  i <- sel[ k ]
  env <- split_paths( p$env[ i ] )
  log <- file.path( logs, paste0( p$id[ i ], ".log" ) )
  cat( format( Sys.time(), "%H:%M:%S" ), " ", p$id[ i ], " ", p$script[ i ], " ", p$args[ i ], "\n", sep = "" )
  t0 <- Sys.time()
  st <- system2( rscript, c( shQuote( p$script[ i ] ), strsplit( trimws( p$args[ i ] ), " +" )[[ 1 ]] ),
                 stdout = log, stderr = log, env = env )
  sec <- as.numeric( difftime( Sys.time(), t0, units = "secs" ) )
  if ( st != 0 ) stop( "step ", p$id[ i ], " failed (exit ", st, "); see ", log )
  if ( !exists_all( p$outs[[ i ]] ) ) stop( "step ", p$id[ i ], " did not write all its outputs; see ", log )
  timing <- rbind( timing, data.frame( id = p$id[ i ], seconds = round( sec ) ) )
  cat( "         done in ", round( sec / 60, 1 ), " min\n", sep = "" )
}
if ( nrow( timing ) ) {
  ft <- file.path( logs, "run_timing.csv" )
  write.csv( cbind( timing, finished = format( Sys.time() ) ), ft, row.names = FALSE )
}

## ---- manifest ------------------------------------------------------------------------------
sha <- function( f ) {
  if ( requireNamespace( "digest", quietly = TRUE ) ) digest::digest( f, "sha256", file = TRUE )
  else paste0( "md5:", unname( tools::md5sum( f ) ) )
}
man <- do.call( rbind, lapply( seq_len( nrow( p ) ), function( i ) {
  fs <- as.character( unlist( lapply( p$outs[[ i ]], expand ) ) ); fs <- fs[ file.exists( fs ) ]
  if ( length( fs ) ) data.frame( path = substring( fs, nchar( BUILD ) + 2 ), bytes = file.size( fs ),
                                  sha256 = vapply( fs, sha, character( 1 ) ), step = p$id[ i ],
                                  modified = format( file.mtime( fs ), "%Y-%m-%d %H:%M:%S" ) ) } ) )
write.csv( man, file.path( BUILD, "MANIFEST.csv" ), row.names = FALSE )
cat( "wrote ", file.path( BUILD, "MANIFEST.csv" ), ": ", nrow( man ), " files\n", sep = "" )
